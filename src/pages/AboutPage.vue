    <h2>Data Collection Process</h2>
    <p>
        This dataset includes a wide swath of transportation demand management projects implemented around Vermont since 2019, from road redesigns that result from years of state and local planning, to small-scale changes spearheaded by community members that make neighborhoods more walkable. There is currently no centralized system tracking new Transportation Demand Management (TDM) infrastructure projects around Vermont. In order to capture projects of all scopes, we drew from a variety of state and local government sources, media reports, and community outreach. Collecting and sharing information about these projects gives communities more opportunities to learn from each other. 
    </p>
    <p>
        The <a href="https://vtrans.vermont.gov/highway/complete-streets" target="_blank">Complete Streets Reporting Tool</a>, managed by the Vermont Agency of Transportation, tracks transportation infrastructure construction projects and how they incorporate the principles of Complete Streets, which include features for bikes and pedestrians. Projects listed in this platform have been contracted, though the list does not note when construction has been completed. While many local authorities contribute to the tracking tool, it does not include all projects in the state. 
    </p>
    <p>
        We reached out to all 11 of Vermont’s regional planning commissions, receiving data from seven. We circulated requests for input to municipal officials, advocacy organizations, and local bike-walk groups around the state. In 2025, we also carried out an online survey, recruiting reports of infrastructure from local officials and planners, bike/walk advocates, and community members across the state. 
    </p>
    <p>
        This dataset includes projects that were awarded funding through federal and state grant programs, including the Bike and Pedestrian Program and the Transportation Alternatives Program, both managed by the Vermont Agency of Transportation, and Agency of Commerce and Community Development programs including the Downtown Transportation Fund and the Better Connections program. We reviewed projects supported by an array of organizations and community groups, including AARP, Chittenden Area Transportation Management Association, Local Motion, the Vermont Natural Resources Council, and Vital Communities. 
    </p>
    <p>
        The dataset also reflects thorough review of coverage of transportation projects in local and statewide news media and posts on social media. We tracked and confirmed projects through other documentary sources, including engineering firm project summaries and updates reported in municipal government documents, such as annual town reports and select board meeting minutes. 
    </p>
    <p>
        Because projects are not tracked centrally, and many are small in scope, this likely does not capture every TDM infrastructure project completed in the state over the last five years. However, it does provide a representative sample of initiatives that have been realized across Vermont communities.
